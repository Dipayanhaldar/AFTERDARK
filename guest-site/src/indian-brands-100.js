/**
 * Merges the base catalog with `ADDITIONAL_INDIAN_BRANDS` and guarantees
 * exactly 100 distinct Top Indian Brands in `brandCatalog`.
 */
export function buildTop100IndianBrandCatalog(baseBrands = []) {
  const map = new Map();
  for (const b of baseBrands) {
    if (b && b.id && !map.has(b.id)) {
      map.set(b.id, b);
    }
  }
  for (const b of ADDITIONAL_INDIAN_BRANDS) {
    if (b && b.id && !map.has(b.id) && map.size < 100) {
      map.set(b.id, b);
    }
  }
  return Array.from(map.values()).slice(0, 100);
}
